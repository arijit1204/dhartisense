"""Assemble a clean, host-neutral deployment bundle in build/bundle/.

Run:  venv/Scripts/python.exe deploy/build_bundle.py [--with-model]

The bundle holds only what the running site needs: the server, the browser app, the few engine and data files, a Dockerfile and a Render blueprint
(render.yaml). It never contains .env, keys, datasets, training code or the virtualenv. The plant-photo model is left out unless you pass --with-model
(its training data has a share-alike licence, see NOTICE.md); the app then uses only the Groq vision check for photos.
The bundle includes the derived crop-data files from ml/models/, so keep any repository you push it to PRIVATE.
"""

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "build" / "bundle"
sys.stdout.reconfigure(encoding="utf-8")

FILES = ["app/__init__.py", "app/__main__.py", "app/server.py", "app/fbstore.py", "app/mailer.py", "app/ndvi.py",
         "ml/__init__.py", "ml/crop_fit.py", "ml/water_plan.py", "ml/nutrient_plan.py",
         "ml/models/crop_requirements.json", "ml/models/regional_crops.json", "LICENSE", "NOTICE.md"]
MODEL = "ml/models/plant_disease_v3.pth"
FOLDERS = ["static"]

DOCKERFILE = """FROM python:3.12-slim
ENV PYTHONUNBUFFERED=1 PYTHONDONTWRITEBYTECODE=1 PIP_NO_CACHE_DIR=1 DHARTISENSE_HOST=0.0.0.0 DHARTISENSE_COOKIE_SECURE=1
RUN useradd -m -u 1000 user
WORKDIR /home/user/app
COPY requirements.txt .
{torch}RUN pip install -r requirements.txt
COPY --chown=user . .
USER user
# the host provides PORT (Render, Cloud Run and others); the server reads it
CMD ["python", "-m", "app.server"]
"""
TORCH = "# CPU-only PyTorch for the plant-photo model\nRUN pip install torch torchvision --index-url https://download.pytorch.org/whl/cpu\n"

RENDER = """# Render blueprint: New > Blueprint, pick this repository. Fill in the values marked "sync: false" when asked.
services:
  - type: web
    name: dhartisense
    runtime: docker
    plan: free
    region: singapore
    healthCheckPath: /api/health
    envVars:
      - key: DHARTISENSE_HOST
        value: 0.0.0.0
      - key: DHARTISENSE_COOKIE_SECURE
        value: "1"
      - key: GROQ_MODEL
        value: openai/gpt-oss-20b
      - key: GROQ_VISION_MODEL
        value: qwen/qwen3.8-27b
      - key: FIREBASE_PROJECT_ID
        sync: false
      - key: FIREBASE_API_KEY
        sync: false
      - key: FIREBASE_SERVICE_ACCOUNT_JSON
        sync: false
      - key: GROQ_API_KEY
        sync: false
"""

README = """# Dhartisense deployment bundle

Generated by deploy/build_bundle.py from the Dhartisense project. Do not edit here; rebuild from the project.
Keep this repository private: it contains derived crop data. Deployment steps: docs/hosting.md in the main project.
"""

REQUIREMENTS = """firebase-admin>=6.5,<7
pillow>=10
"""


def main():
    with_model = "--with-model" in sys.argv
    OUT.mkdir(parents=True, exist_ok=True)
    for child in OUT.iterdir():  # rebuild from scratch but keep the git history of the deploy repository
        if child.name != ".git":
            shutil.rmtree(child) if child.is_dir() else child.unlink()
    for name in FILES + ([MODEL] if with_model else []):
        source = ROOT / name
        if not source.exists():
            sys.exit(f"Missing {name}: cannot build the bundle (see docs/data-setup.md).")
        (OUT / name).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, OUT / name)
    for folder in FOLDERS:
        shutil.copytree(ROOT / folder, OUT / folder, ignore=shutil.ignore_patterns("*.pyc", "__pycache__"))
    (OUT / "Dockerfile").write_text(DOCKERFILE.format(torch=TORCH if with_model else ""), encoding="utf-8")
    (OUT / "render.yaml").write_text(RENDER, encoding="utf-8")
    (OUT / "README.md").write_text(README, encoding="utf-8")
    (OUT / "requirements.txt").write_text(REQUIREMENTS, encoding="utf-8")
    (OUT / ".gitignore").write_text(".env\n*.pem\n*-firebase-adminsdk-*.json\n__pycache__/\n", encoding="utf-8")
    total = sum(f.stat().st_size for f in OUT.rglob("*") if f.is_file())
    print(f"Built {OUT} ({sum(1 for f in OUT.rglob('*') if f.is_file())} files, {total / 1e6:.1f} MB, plant model {'included' if with_model else 'left out'})")
    leaks = [f for f in OUT.rglob("*") if f.name == ".env" or (f.suffix == ".json" and "adminsdk" in f.name)]
    if leaks:
        sys.exit(f"Refusing: secret-looking files in the bundle: {leaks}")


if __name__ == "__main__":
    main()
